/**
 * @fileoverview Zero-dependency build script that generates `src/config/runtimeEnv.js`
 * by merging `config/env.defaults.json` with `.env` (if present) and `process.env`.
 *
 * Usage:
 *   node scripts/generate-env.mjs
 *   npm run env:build
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const DEFAULTS_PATH = path.join(ROOT_DIR, 'config', 'env.defaults.json');
const DOTENV_PATH = path.join(ROOT_DIR, '.env');
const OUTPUT_PATH = path.join(ROOT_DIR, 'src', 'config', 'runtimeEnv.js');

/**
 * Parses a `.env` file content string into a key-value map.
 * Supports comments (`#`), blank lines, and single/double-quoted values.
 *
 * @param {string} raw - Raw file contents.
 * @returns {Record<string, string>} Parsed environment variables.
 */
export function parseDotEnv(raw) {
  const vars = {};
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const eqIndex = trimmed.indexOf('=');
    if (eqIndex <= 0) continue;

    const key = trimmed.slice(0, eqIndex).trim();
    let value = trimmed.slice(eqIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    vars[key] = value;
  }
  return vars;
}

/**
 * Parses a positive integer safely or returns fallback.
 *
 * @param {string | undefined} rawValue
 * @param {number} fallback
 * @returns {number}
 */
function toInt(rawValue, fallback) {
  if (rawValue === undefined || rawValue === '') return fallback;
  const parsed = Number.parseInt(rawValue, 10);
  return Number.isFinite(parsed) && parsed >= 0 ? parsed : fallback;
}

/**
 * Builds the merged runtime config object from defaults + env overrides.
 *
 * @param {object} defaults
 * @param {Record<string, string | undefined>} env
 * @returns {object}
 */
export function buildRuntimePayload(defaults, env) {
  return {
    appEnv: env.APP_ENV || null,
    appName: env.APP_NAME || defaults.appName,
    appVersion: defaults.appVersion,
    siteUrl: env.SITE_URL || defaults.siteUrl,
    contactRecipientEmail: env.CONTACT_RECIPIENT_EMAIL || defaults.contactRecipientEmail,
    api: {
      baseUrl: env.API_BASE_URL ?? defaults.api.baseUrl,
      timeoutMs: toInt(env.API_TIMEOUT_MS, defaults.api.timeoutMs),
      maxRetries: toInt(env.API_MAX_RETRIES, defaults.api.maxRetries),
      retryDelayMs: toInt(env.API_RETRY_DELAY_MS, defaults.api.retryDelayMs),
      endpoints: {
        googleAppsScriptUrl:
          env.GOOGLE_APPS_SCRIPT_URL ?? defaults.api.endpoints.googleAppsScriptUrl,
        formSubmitUrl:
          env.FORMSUBMIT_ENDPOINT ?? defaults.api.endpoints.formSubmitUrl
      }
    },
    contact: {
      cooldownMs: toInt(env.CONTACT_COOLDOWN_MS, defaults.contact.cooldownMs),
      maxHistory: toInt(env.CONTACT_MAX_HISTORY, defaults.contact.maxHistory),
      locale: defaults.contact.locale,
      timeZone: defaults.contact.timeZone
    },
    storage: {
      themeKey: env.THEME_STORAGE_KEY || defaults.storage.themeKey,
      inquiriesKey: env.INQUIRY_STORAGE_KEY || defaults.storage.inquiriesKey,
      cooldownKey: env.COOLDOWN_STORAGE_KEY || defaults.storage.cooldownKey
    },
    theme: defaults.theme,
    environments: defaults.environments,
    overrides: {
      logLevel: env.LOG_LEVEL || null
    }
  };
}

function main() {
  if (!fs.existsSync(DEFAULTS_PATH)) {
    throw new Error(`Missing defaults file at ${DEFAULTS_PATH}`);
  }

  const defaults = JSON.parse(fs.readFileSync(DEFAULTS_PATH, 'utf8'));
  const dotEnvVars = fs.existsSync(DOTENV_PATH)
    ? parseDotEnv(fs.readFileSync(DOTENV_PATH, 'utf8'))
    : {};

  // process.env overrides .env file, which overrides config/env.defaults.json
  const mergedEnv = { ...dotEnvVars, ...process.env };
  const payload = buildRuntimePayload(defaults, mergedEnv);

  const fileHeader = [
    '/**',
    ' * AUTO-GENERATED RUNTIME ENVIRONMENT CONFIG.',
    ' * Generated by `scripts/generate-env.mjs` from `config/env.defaults.json` and `.env`.',
    ' * Safe for static browser execution & synchronous pre-paint theme initialization.',
    ' */',
    '(function initRuntimeEnv(globalScope) {',
    '  const existing = globalScope.__PORTFOLIO_RUNTIME_ENV__ || {};',
    `  const generated = ${JSON.stringify(payload, null, 2)};`,
    '  globalScope.__PORTFOLIO_RUNTIME_ENV__ = Object.assign({}, generated, existing);',
    '})(typeof globalThis !== "undefined" ? globalThis : window);',
    ''
  ].join('\n');

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, fileHeader, 'utf8');
  console.log(`Generated ${path.relative(ROOT_DIR, OUTPUT_PATH)} successfully.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main();
}

